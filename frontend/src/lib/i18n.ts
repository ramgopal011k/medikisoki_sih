export type Language = 'en' | 'hi' | 'mr' | 'bn';

export function getTranslation(key: string, lang: Language = 'en', fallback?: string): string {
  const dict = DICTIONARY[lang] as Record<string, string> | undefined;
  if (dict && dict[key]) return dict[key];
  const enDict = DICTIONARY.en as Record<string, string>;
  if (enDict[key]) return enDict[key];
  return fallback || key;
}

export function useTranslation(overrideLang?: Language) {
  const storedLang = (typeof localStorage !== 'undefined' ? localStorage.getItem('patient_language') : null) || 'en';
  const rawLang = overrideLang || storedLang;
  const lang: Language = (rawLang === 'hi' || rawLang === 'mr' || rawLang === 'bn') ? rawLang : 'en';
  
  const t = (key: string, fallback?: string): string => {
    return getTranslation(key, lang, fallback);
  };

  return { t, lang };
}
